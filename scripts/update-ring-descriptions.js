// Функция для построения slug товара (аналогично buildProductSlug из seo.js)
function buildProductSlug(product) {
    const typeMap = {
        'ring': 'kolcza',
        'necklace': 'kole',
        'earrings': 'sergi',
        'bracelets': 'braslety'
    };
    
    const typeSlug = typeMap[product.type] || product.type;
    
    const nameSlug = product.name
        .toLowerCase()
        .replace(/\s+/g, '-')
        .replace(/[а-яё]/g, (char) => {
            const map = {
                'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
                'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 
                'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
                'ф': 'f', 'х': 'h', 'ц': 'c', 'ч': 'ch', 'ш': 'sh', 'щ': 'sch',
                'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'
            };
            return map[char] || char;
        });
    
    return `${typeSlug}-${nameSlug}`;
}

async function updateRingDescriptions() {
    if (!ADMIN_TOKEN) {
        console.error('❌ Ошибка: ADMIN_TOKEN не установлен. Установите его через переменную окружения:');
        console.error('   $env:ADMIN_TOKEN="ваш_токен" (PowerShell)');
        console.error('   или export ADMIN_TOKEN="ваш_токен" (Bash)');
        process.exit(1);
    }

    try {
        console.log('🔍 Загрузка всех товаров...');
        
        const response = await axios.get(`${API_BASE_URL}getProducts`);
        const products = response.data;

        if (!Array.isArray(products)) {
            console.error('❌ Ошибка: товары не получены');
            return;
        }

        console.log(`✅ Загружено ${products.length} товаров`);

        // Фильтруем только кольца
        const rings = products.filter(p => p.type === 'ring');
        console.log(`📦 Найдено ${rings.length} колец`);

        let updatedCount = 0;
        let notFoundCount = 0;
        const notFoundSlugs = [];

        for (const [productName, newDescription] of Object.entries(descriptionsMap)) {
            // Находим товар по имени
            const product = rings.find(p => p.name === productName);

            if (!product) {
                console.warn(`⚠️  Товар с именем "${productName}" не найден`);
                notFoundCount++;
                notFoundSlugs.push(productName);
                continue;
            }

            // Проверяем, нужно ли обновление
            if (product.description === newDescription) {
                console.log(`✓ Товар "${product.name}" уже имеет актуальное описание, пропускаем`);
                continue;
            }

            const slug = buildProductSlug(product);
            console.log(`\n🔄 Обновление товара: ${product.name} (${slug})`);

            // Получаем полные данные товара
            const fullProductResponse = await axios.post(`${API_BASE_URL}getOneProduct`, { id: product._id });
            const fullProductData = fullProductResponse.data;

            // Обновляем описание
            const updatedProductPayload = {
                ...fullProductData,
                description: newDescription
            };

            // Создаем FormData для обновления
            const formData = new FormData();
            formData.append('data', JSON.stringify(updatedProductPayload));

            // Добавляем существующие изображения
            if (fullProductData.cover) {
                formData.append('coverNames', fullProductData.cover);
            }
            if (Array.isArray(fullProductData.images)) {
                fullProductData.images.forEach((img, index) => {
                    if (typeof img === 'string') {
                        formData.append(`imageNames[${index}]`, img);
                    }
                });
            }

            // Отправляем обновление
            await axios.post(`${API_BASE_URL}editProduct`, formData, {
                headers: {
                    Authorization: `Bearer ${ADMIN_TOKEN}`,
                    ...formData.getHeaders()
                }
            });

            console.log(`✅ Описание успешно обновлено для "${product.name}"`);
            updatedCount++;

            // Небольшая задержка между запросами
            await new Promise(resolve => setTimeout(resolve, 500));
        }

        console.log('\n' + '='.repeat(50));
        console.log('📊 Итоги:');
        console.log(`   ✅ Обновлено товаров: ${updatedCount}`);
        console.log(`   ⚠️  Не найдено товаров: ${notFoundCount}`);
        
        if (notFoundSlugs.length > 0) {
            console.log('\n   Не найденные slug:');
            notFoundSlugs.forEach(slug => console.log(`      - ${slug}`));
        }
        
        console.log('='.repeat(50));

    } catch (error) {
        console.error('❌ Ошибка при обновлении описаний:', error.message);
        if (error.response) {
            console.error('   Детали ошибки:', error.response.data);
        }
        process.exit(1);
    }
}

// Запуск скрипта
updateRingDescriptions();

